function contactApiPlugin(): Plugin {
  return {
    name: 'vite-plugin-contact-api',
    configureServer(server) {
      server.middlewares.use(async (req, res, next) => {
        const url = req.url?.split('?')[0];
        if (url === '/api/contact' && req.method === 'POST') {
          let body = '';
          req.on('data', (chunk) => {
            body += chunk;
          });
          req.on('end', async () => {
            try {
              const parsedBody = body ? JSON.parse(body) : {};
              const { handleContactInquiry } = await import(
                './src/api/contactHandler.js'
              );
              const ip = (req.headers['x-forwarded-for'] as string) || req.socket?.remoteAddress || '';
              const result = await handleContactInquiry(parsedBody, ip);
              res.setHeader('Content-Type', 'application/json');
              res.statusCode = result.status;
              res.end(JSON.stringify(result.data));
            } catch {
              res.setHeader('Content-Type', 'application/json');
              res.statusCode = 500;
              res.end(
                JSON.stringify({
                  success: false,
                  error: 'Server error processing inquiry. Please try again or email directly.',
                }),
              );
            }
          });
          return;
        }

        if (url === '/api/health' && req.method === 'GET') {
          res.setHeader('Content-Type', 'application/json');
          res.statusCode = 200;
          res.end(
            JSON.stringify({
              status: 'ok',
              service: 'pratiksha-portfolio-backend',
            }),
          );
          return;
        }

        next();
      });
    },
  };
}

